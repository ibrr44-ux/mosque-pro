function t(key) {
  if (translations[currentLang] && translations[currentLang][key] !== undefined) {
    return translations[currentLang][key];
  }
  if (translations.ar[key] !== undefined) return translations.ar[key];
  return key;
}

function setLanguage(lang) {
  if (lang !== 'ar' && lang !== 'en') return;
  currentLang = lang;
  localStorage.setItem('mosqueLang', lang);
  var dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.dir = dir;
  document.documentElement.lang = lang === 'ar' ? 'ar' : 'en';
  applyLanguage();
  if (typeof App !== 'undefined' && App.refresh) {
    App.refresh();
  }
}

function applyLanguage() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    var key = el.dataset.i18nPlaceholder;
    if (key) el.placeholder = t(key);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
    var key = el.dataset.i18nTitle;
    if (key) el.title = t(key);
  });
  var langToggle = document.getElementById('langToggle');
  if (langToggle) {
    var isEn = currentLang === 'en';
    langToggle.innerHTML = isEn ? '<i class="fas fa-language"></i> العربية' : '<i class="fas fa-language"></i> English';
  }
  var themeSpan = document.querySelector('#darkModeToggle span');
  if (themeSpan) {
    var isDark = document.body.classList.contains('dark');
    themeSpan.textContent = isDark ? t('lightMode') : t('darkMode');
  }
}
